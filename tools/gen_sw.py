"""Regenerate sw.js.

The service worker precaches the whole app shell by name, so the list has to be
rebuilt whenever a file is added to vendor/ or icons/. The cache version is a
hash of everything in that list, which means any content change ships as a new
cache and readers get the "new version" button -- there is no version number to
forget to bump.

Run it after building the pages:  python3 tools/gen_sw.py
"""

import hashlib
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent

# Entries that are not discovered by globbing.
ROOT_FILES = [
    "./",
    "index.html",
    "english.html",
    "manifest.webmanifest",
    "book-ar.md",
    "book.md",
    "vendor/marked.min.js",
    "vendor/katex/katex.min.css",
    "vendor/katex/katex.min.js",
    "vendor/fonts-ar.css",
    "vendor/fonts-en.css",
    "icons/icon-192.png",
    "icons/icon-512.png",
    "icons/icon-maskable-512.png",
    "icons/apple-touch-icon.png",
]

TEMPLATE = """/* Service worker for the ML math book. Generated by tools/gen_sw.py.

   Everything the book needs is same-origin and vendored, so the whole app
   works with no network at all once it has been opened once. CACHE is keyed by
   a hash of the precached files, so a rebuild automatically supersedes the
   previous cache instead of relying on a hand-bumped version. */
'use strict';

var CACHE = 'mlmath-__VERSION__';

/* KaTeX ships one woff2 per font face; the book can reach any of them. */
var KATEX_FONTS = [
__KATEX__
].map(function (name) { return 'vendor/katex/fonts/KaTeX_' + name + '.woff2'; });

/* Google Fonts woff2, vendored. Hashed names come straight from Google's CSS. */
var WEB_FONTS = [
__GFONTS__
].map(function (name) { return 'vendor/fonts/' + name; });

var PRECACHE = [
__ROOT__
].concat(KATEX_FONTS, WEB_FONTS);

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      /* Request each entry separately: one 404 should not void the whole install. */
      return Promise.all(PRECACHE.map(function (url) {
        return cache.add(new Request(url, { cache: 'reload' })).catch(function (err) {
          console.warn('[sw] could not precache', url, err);
        });
      }));
    })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (key) {
        if (key !== CACHE && key.indexOf('mlmath-') === 0) return caches.delete(key);
      }));
    }).then(function () {
      return self.clients.claim();
    })
  );
});

/* The page asks for this once the reader accepts a waiting update. */
self.addEventListener('message', function (event) {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

function revalidate(cache, request) {
  return fetch(request).then(function (response) {
    if (response && response.ok && response.type === 'basic') {
      return cache.put(request, response.clone()).then(function () { return response; });
    }
    return response;
  }).catch(function () { return null; });
}

/* Cache first, refresh in the background: the book opens instantly offline and
   still picks up a new build on the next visit. */
function respond(event, request) {
  return caches.open(CACHE).then(function (cache) {
    return cache.match(request, { ignoreSearch: true }).then(function (cached) {
      if (cached) {
        event.waitUntil(revalidate(cache, request));
        return cached;
      }
      return revalidate(cache, request).then(function (response) {
        if (response) return response;
        if (request.mode === 'navigate') {
          return cache.match('index.html').then(function (shell) {
            return shell || Response.error();
          });
        }
        return Response.error();
      });
    });
  });
}

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(respond(event, request));
});
"""


def js_list(items):
    return "\n".join("  '%s'," % item for item in items).rstrip(",")


def main():
    katex = sorted(p.stem.replace("KaTeX_", "") for p in (REPO / "vendor/katex/fonts").glob("*.woff2"))
    gfonts = sorted(p.name for p in (REPO / "vendor/fonts").glob("*.woff2"))

    urls = (ROOT_FILES
            + ["vendor/katex/fonts/KaTeX_%s.woff2" % n for n in katex]
            + ["vendor/fonts/%s" % n for n in gfonts])

    # "./" is index.html under another name; everything else must be a real file.
    missing = [u for u in urls if u != "./" and not (REPO / u).is_file()]
    if missing:
        sys.exit("missing files, refusing to write sw.js:\n  " + "\n  ".join(missing))

    duplicates = sorted({u for u in urls if urls.count(u) > 1})
    if duplicates:
        sys.exit("duplicate precache entries: %s" % ", ".join(duplicates))

    digest = hashlib.sha256()
    for url in urls:
        source = REPO / ("index.html" if url == "./" else url)
        digest.update(url.encode("utf-8"))
        digest.update(source.read_bytes())
    version = digest.hexdigest()[:12]

    sw = (TEMPLATE
          .replace("__KATEX__", js_list(katex))
          .replace("__GFONTS__", js_list(gfonts))
          .replace("__ROOT__", js_list(ROOT_FILES))
          .replace("__VERSION__", version))
    (REPO / "sw.js").write_text(sw, encoding="utf-8")

    payload = sum((REPO / ("index.html" if u == "./" else u)).stat().st_size for u in urls)
    print("sw.js written: cache mlmath-%s, %d URLs, %.2f MB precached"
          % (version, len(urls), payload / 1048576))


if __name__ == "__main__":
    main()
